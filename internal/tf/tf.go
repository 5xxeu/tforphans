// Runner runs terraform in one root module directory.
type Runner struct {
	Bin string
	Dir string
	// Workspace selects a workspace through TF_WORKSPACE, which leaves the
	// module's selected workspace untouched. Empty means the selected one.
	Workspace string
	// Env is added to the environment of every command.
	Env []string
	// Isolated marks a generated root: the user's TF_DATA_DIR and
	// TF_WORKSPACE must not reach it, so its data stays in its own
	// directory.
	Isolated bool
	// AnyVersion lifts the root module's required_version for each
	// command with a temporary override file: a root pinned to an older
	// Terraform would refuse terraform query.
	AnyVersion bool
	// MaxStateSize bounds state pull and refresh output; zero uses the default.
	MaxStateSize int64
	// MaxQuerySize bounds terraform query output; zero uses the default.
	MaxQuerySize int64
}

// versionOverride relaxes required_version; override files replace the
// root module's constraints.
const versionOverride = "# Generated by tforphans; removed after the command.\nterraform {\n  required_version = \">= 0\"\n}\n"

// Exec runs terraform with args and returns stdout and stderr.
func (r Runner) Exec(ctx context.Context, args ...string) ([]byte, []byte, error) {
	out, stderr, err := r.run(ctx, args...)
	if err != nil {
		err = cmdError(args, stderr, err)
	}
	return out, stderr, err
}

func (r Runner) run(ctx context.Context, args ...string) ([]byte, []byte, error) {
	return r.runLimited(ctx, 0, args...)
}

func (r Runner) stateSize() int64 {
	if r.MaxStateSize == 0 {
		return state.DefaultMaxSize
	}
	return r.MaxStateSize
}

func (r Runner) runLimited(ctx context.Context, maxSize int64, args ...string) ([]byte, []byte, error) {
	if maxSize == 0 {
		cmd, stderr, cleanup, err := r.command(ctx, args...)
		if err != nil {
			return nil, nil, err
		}
		defer cleanup()
		var stdout bytes.Buffer
		cmd.Stdout = &stdout
		err = cmd.Run()
		return stdout.Bytes(), stderr.Bytes(), err
	}
	var out []byte
	stderr, err := r.stream(ctx, func(pipe io.Reader) error {
		data, readErr := state.ReadLimited(pipe, maxSize)
		if readErr == nil {
			out = data
		}
		return readErr
	}, args...)
	return out, stderr, err
}

// stream runs terraform and hands its stdout to consume while it runs
// (proc.Stream: the process is stopped when consume fails).
func (r Runner) stream(ctx context.Context, consume func(io.Reader) error, args ...string) ([]byte, error) {
	cmd, stderr, cleanup, err := r.command(ctx, args...)
	if err != nil {
		return nil, err
	}
	defer cleanup()
	err = proc.Stream(ctx, cmd, consume)
	if ctx.Err() != nil {
		return stderr.Bytes(), ctx.Err()
	}
	return stderr.Bytes(), err
}

// command prepares terraform with args: environment, process group, the
// required_version override; cleanup removes what it wrote.
func (r Runner) command(ctx context.Context, args ...string) (*exec.Cmd, *proc.StderrBuffer, func(), error) {
	var files []string
	runCtx, cancel := context.WithCancel(ctx)
	cleanup := func() {
		cancel()
		for _, f := range files {
			os.Remove(f)
		}
	}
	if r.AnyVersion {
		name := tempName(tempVersionSuffix)
		// Override files apply in name order; one after ours could set
		// required_version again.
		if later := laterOverrides(r.Dir, name); len(later) > 0 {
			cancel()
			return nil, nil, nil, fmt.Errorf("-ignore-required-version: %s applies after tforphans' override file and may set required_version again; rename it or relax the constraint", strings.Join(later, ", "))
		}
		path := filepath.Join(r.Dir, name)
		if err := writeTemp(path, []byte(versionOverride)); err != nil {
			cancel()
			return nil, nil, nil, err
		}
		files = append(files, path)
	}
	cmd := exec.CommandContext(runCtx, r.Bin, args...)
	// A wrapper given with -terraform may run terraform as its child.
	proc.Group(cmd)
	cmd.Dir = r.Dir
	cmd.Env = append(Environ(os.Environ(), r.Isolated), "TF_IN_AUTOMATION=1")
	if r.Workspace != "" {
		cmd.Env = append(cmd.Env, "TF_WORKSPACE="+r.Workspace)
	}
	cmd.Env = append(cmd.Env, r.Env...)
	stderr := &proc.StderrBuffer{}
	cmd.Stderr = stderr
	return cmd, stderr, cleanup, nil
}

// laterOverrides returns the override files of dir whose names sort after
// name, other than tforphans' own.
func laterOverrides(dir, name string) []string {
	entries, _ := os.ReadDir(dir)
	var out []string
	for _, e := range entries {
		n := e.Name()
		// Only .tf and .tf.json files are configuration.
		base, ok := strings.CutSuffix(n, ".tf.json")
		if !ok {
			base, ok = strings.CutSuffix(n, ".tf")
		}
		if !ok || e.IsDir() || IgnoredFile(n) || strings.HasPrefix(n, "zz_tforphans_") || !(base == "override" || strings.HasSuffix(base, "_override")) {
			continue
		}
		if n > name {
			out = append(out, n)
		}
	}
	return out
}

func cmdError(args []string, stderr []byte, err error) error {
	msg := strings.TrimSpace(string(stderr))
	if msg == "" {
		return fmt.Errorf("terraform %s: %w", strings.Join(args, " "), err)
	}
	if strings.Contains(msg, "Unsupported Terraform Core version") {
		msg += "\n(a required_version rejects this terraform: use a version it allows; when it is the root's own, -ignore-required-version overrides it for this run, a child module's constraint it cannot)"
	}
	return fmt.Errorf("terraform %s: %w\n%s", strings.Join(args, " "), err, msg)
}

// StatePull returns the raw state of r.Workspace.
func (r Runner) StatePull(ctx context.Context) ([]byte, error) {
	args := []string{"state", "pull", "-no-color"}
	out, stderr, err := r.runLimited(ctx, r.stateSize(), args...)
	if err != nil {
		return nil, cmdError(args, stderr, err)
	}
	return out, nil
}

// RefreshedState returns `terraform show -json` of a refresh-only plan: the
// state as the providers see it now, with resource identities that the
// stored state may lack. Nothing is written to the stored state and no lock
// is taken; the plan file, which holds the state's values, lives in a
// private temporary directory that is removed afterwards.
func (r Runner) RefreshedState(ctx context.Context) ([]byte, error) {
	dir, err := os.MkdirTemp("", "tforphans-refresh-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(dir)
	planFile := filepath.Join(dir, "refresh.tfplan")
	args := []string{"plan", "-refresh-only", "-lock=false", "-input=false", "-no-color", "-out=" + planFile}
	if _, stderr, err := r.run(ctx, args...); err != nil {
		return nil, cmdError(args, stderr, err)
	}
	args = []string{"show", "-json", "-no-color", planFile}
	out, stderr, err := r.runLimited(ctx, r.stateSize(), args...)
	if err != nil {
		return nil, cmdError(args, stderr, err)
	}
	return out, nil
}

// Schemas is the subset of `terraform providers schema -json` we use.
type Schemas struct {
	ProviderSchemas map[string]ProviderSchema `json:"provider_schemas"`
}

type ProviderSchema struct {
	ListResourceSchemas     map[string]ListSchema     `json:"list_resource_schemas"`
	ResourceIdentitySchemas map[string]IdentitySchema `json:"resource_identity_schemas"`
	ResourceSchemas         map[string]struct {
		Block struct {
			Attributes map[string]json.RawMessage `json:"attributes"`
		} `json:"block"`
	} `json:"resource_schemas"`
}

type ListSchema struct {
	Block struct {
		Attributes map[string]struct {
			Type     json.RawMessage `json:"type"`
			Required bool            `json:"required"`
		} `json:"attributes"`
		BlockTypes map[string]struct {
			MinItems int `json:"min_items"`
		} `json:"block_types"`
	} `json:"block"`
}

type IdentitySchema struct {
	Attributes map[string]struct {
		RequiredForImport bool `json:"required_for_import"`
	} `json:"attributes"`
}

// ProvidersSchema returns the schemas of all providers the module uses. The
// module must be initialized.
func (r Runner) ProvidersSchema(ctx context.Context) (*Schemas, error) {
	args := []string{"providers", "schema", "-json", "-no-color"}
	out, stderr, err := r.run(ctx, args...)
	if err != nil {
		return nil, cmdError(args, stderr, err)
	}
	var s Schemas
	if err := json.Unmarshal(out, &s); err != nil {
		return nil, fmt.Errorf("decode provider schemas: %w", err)
	}
	return &s, nil
}

// IdentityKeys are, per resource type, the identity attributes required for
// import (Required), and those of them that are also resource attributes
// (Attribute), which are the ones state without an identity can be checked
// against. azurerm identities, for example, carry subscription_id, which is
// never an attribute.
//
// Two providers can define the same type (google and google-beta) with
// different identities, so keys are kept per provider address; Required
// and Attribute hold, per type, the union over all providers, for objects
// whose provider is unknown: more keys can only make an object unmanaged,
// never managed by mistake.
type IdentityKeys struct {
	Required   map[string][]string
	Attribute  map[string][]string
	ByProvider map[string]IdentityKeys
}

// For returns the keys of a type of the provider at an address, or the
// union over providers when the address is "" or unknown.
func (k IdentityKeys) For(provider, typ string) (required, attribute []string) {
	if pk, ok := k.ByProvider[provider]; ok {
		if r, ok := pk.Required[typ]; ok {
			return r, pk.Attribute[typ]
		}
	}
	return k.Required[typ], k.Attribute[typ]
}

func (s *Schemas) IdentityKeys() IdentityKeys {
	k := IdentityKeys{Required: map[string][]string{}, Attribute: map[string][]string{}, ByProvider: map[string]IdentityKeys{}}
	for addr, p := range s.ProviderSchemas {
		pk := IdentityKeys{Required: map[string][]string{}, Attribute: map[string][]string{}}
		k.ByProvider[addr] = pk
		for typ, is := range p.ResourceIdentitySchemas {
			required, attribute := []string{}, []string{}
			attrs := p.ResourceSchemas[typ].Block.Attributes
			for name, a := range is.Attributes {
				if !a.RequiredForImport {
					continue
				}
				required = append(required, name)
				if _, ok := attrs[name]; ok {
					attribute = append(attribute, name)
				}
			}
			sort.Strings(required)
			sort.Strings(attribute)
			pk.Required[typ], pk.Attribute[typ] = required, attribute
			k.Required[typ] = union(k.Required[typ], required)
			k.Attribute[typ] = union(k.Attribute[typ], attribute)
		}
	}
	return k
}

// union returns the sorted union of two key lists, never nil: an empty
// AttributeKeys means "no key is an attribute", nil means "not known".
func union(a, b []string) []string {
	out := append(append([]string{}, a...), b...)
	sort.Strings(out)
	return slices.Compact(out)
}

// LocalNames maps provider addresses (registry.terraform.io/ns/type) to the
// local names declared in the module's required_providers block.
func LocalNames(dir string) (map[string]string, error) {
	mod, diags := tfconfig.LoadModule(dir)
	if diags.HasErrors() {
		return nil, fmt.Errorf("read %s: %w", dir, diags.Err())
	}
	out := map[string]string{}
	// Two local names may require one source (terraform warns): the first
	// by name is the one generated blocks use, whatever the map order.
	for _, name := range slices.Sorted(maps.Keys(mod.RequiredProviders)) {
		if req := mod.RequiredProviders[name]; req.Source != "" {
			if _, seen := out[NormalizeSource(req.Source)]; !seen {
				out[NormalizeSource(req.Source)] = name
			}
		}
	}
	return out, nil
}

// SourceConfigs are the configurations the root module gives a provider:
// terraform keys them by provider address, so every local name of one
// source (terraform warns about two) refers to the same ones.
type SourceConfigs struct {
	// Plain is set when some provider block has no alias; a source with
	// aliases only would get an empty default configuration.
	Plain bool
	// Aliases of every provider block of the source, with the local name
	// they are declared under: blocks refer to them through it.
	Aliases []ConfigRef
	// LocalNames are the names required_providers gives the source; more
	// than one makes terraform resolve its configurations unreliably.
	LocalNames []string
}

// ConfigRef is an aliased provider configuration: local name and alias.
type ConfigRef struct{ Local, Alias string }

// Ref is how a block refers to it: aws.prod.
func (c ConfigRef) Ref() string { return c.Local + "." + c.Alias }

// ProviderSourceConfigs maps provider addresses to their configurations
// in the root module's provider blocks.
func ProviderSourceConfigs(dir string) (map[string]SourceConfigs, error) {
	mod, diags := tfconfig.LoadModule(dir)
	if diags.HasErrors() {
		return nil, fmt.Errorf("read %s: %w", dir, diags.Err())
	}
	out := map[string]SourceConfigs{}
	for _, pc := range mod.ProviderConfigs {
		addr := "registry.terraform.io/hashicorp/" + pc.Name
		if req, ok := mod.RequiredProviders[pc.Name]; ok && req.Source != "" {
			addr = NormalizeSource(req.Source)
		}
		c := out[addr]
		if pc.Alias == "" {
			c.Plain = true
		} else if ref := (ConfigRef{pc.Name, pc.Alias}); !slices.Contains(c.Aliases, ref) {
			c.Aliases = append(c.Aliases, ref)
		}
		out[addr] = c
	}
	for name, req := range mod.RequiredProviders {
		if req.Source != "" {
			addr := NormalizeSource(req.Source)
			c := out[addr]
			c.LocalNames = append(c.LocalNames, name)
			out[addr] = c
		}
	}
	// A provider block of a name not in required_providers is the implicit
	// hashicorp/<name>: one more name of that source.
	for _, pc := range mod.ProviderConfigs {
		if req, ok := mod.RequiredProviders[pc.Name]; !ok || req.Source == "" {
			addr := "registry.terraform.io/hashicorp/" + pc.Name
			if c := out[addr]; !slices.Contains(c.LocalNames, pc.Name) {
				c.LocalNames = append(c.LocalNames, pc.Name)
				out[addr] = c
			}
		}
	}
	for _, c := range out {
		slices.SortFunc(c.Aliases, func(a, b ConfigRef) int { return strings.Compare(a.Ref(), b.Ref()) })
		sort.Strings(c.LocalNames)
	}
	return out, nil
}

// NormalizeSource expands "ns/type" to "registry.terraform.io/ns/type".
func NormalizeSource(src string) string {
	src = strings.ToLower(src)
	if strings.Count(src, "/") == 1 {
		return "registry.terraform.io/" + src
	}
	return src
}

// localName resolves the name a list block's provider argument must use:
// the root module's required_providers entry, the implicit hashicorp/<type>
// mapping, or else a temporary name (local names allow letters, digits and
// dashes, so the prefix cannot clash with a type-derived name).
// used holds the local names taken so far, so that temporary names are
// unique: ns1/foo and ns2/foo become tfo-ns1-foo and tfo-ns2-foo.
func localName(addr string, declared map[string]string, used map[string]bool) (name string, temporary bool) {
	if n, ok := declared[addr]; ok {
		return n, false
	}
	parts := strings.Split(addr, "/")
	if len(parts) == 3 && parts[0] == "registry.terraform.io" && parts[1] == "hashicorp" {
		// The implicit name works unless the root gave it to another
		// provider (google = { source = "hashicorp/google-beta" }).
		taken := false
		for a, n := range declared {
			if n == parts[2] && a != addr {
				taken = true
			}
		}
		if !taken {
			return parts[2], false
		}
	}
	base := "tfo-" + nonLocal.ReplaceAllString(strings.ToLower(strings.Join(parts[1:], "-")), "-")
	name = base
	for i := 2; used[name]; i++ {
		name = fmt.Sprintf("%s-%d", base, i)
	}
	used[name] = true
	return name, true
}

// nonLocal matches what a provider local name may not contain.
var nonLocal = regexp.MustCompile(`[^a-z0-9-]+`)

// Environ filters the environment for terraform. TF_CLI_ARGS and
// TF_CLI_ARGS_<command> are always dropped: they would add arguments to the
// commands tforphans runs (TF_CLI_ARGS_apply="-state-out=prod.tfstate"
// would make the data source scan write over a real state). For isolated
// roots TF_DATA_DIR and TF_WORKSPACE are dropped too.
func Environ(env []string, isolated bool) []string {
	out := make([]string, 0, len(env))
	for _, kv := range env {
		name, _, _ := strings.Cut(kv, "=")
		switch {
		case name == "TF_CLI_ARGS", strings.HasPrefix(name, "TF_CLI_ARGS_"):
		case isolated && (name == "TF_DATA_DIR" || name == "TF_WORKSPACE"):
		default:
			out = append(out, kv)
		}
	}
	return out
}

// ConfigAddresses returns the <type>.<name> addresses of managed resources
// declared in the module's own configuration (not in child modules).
func ConfigAddresses(dir string) (map[string]bool, error) {
	mod, diags := tfconfig.LoadModule(dir)
	if diags.HasErrors() {
		return nil, fmt.Errorf("read %s: %w", dir, diags.Err())
	}
	out := map[string]bool{}
	for addr := range mod.ManagedResources {
		out[addr] = true
	}
	return out, nil
}
